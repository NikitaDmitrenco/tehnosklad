import { notFound } from "next/navigation";

import { CategoryForm } from "@/components/admin/admin-forms";
import { AdminNotice, AdminPageHeader } from "@/components/admin/admin-ui";
import { ConfirmSubmitButton } from "@/components/admin/confirm-submit-button";
import { SubmitButton } from "@/components/admin/submit-button";
import {
  setCategoryArchivedAction,
  uploadCategoryImageAction,
} from "@/features/admin/actions";
import { requireAdmin } from "@/features/admin/auth/guard";
import {
  getAdminCategory,
  listAdminCategories,
} from "@/features/admin/repository";
import { isUuid } from "@/features/admin/validation";

export const dynamic = "force-dynamic";

export default async function CategoryPage({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ error?: string; saved?: string }>;
}) {
  await requireAdmin();
  const { id } = await params;
  if (!isUuid(id)) notFound();
  const [category, categories, query] = await Promise.all([
    getAdminCategory(id),
    listAdminCategories(),
    searchParams,
  ]);
  if (!category) notFound();
  return (
    <main className="admin-content" id="admin-main">
      <AdminPageHeader
        description={`ID: ${category.id}`}
        title={category.translations.ru?.name ?? "Категория"}
      />
      <AdminNotice {...query} />
      <CategoryForm categories={categories} category={category} />
      <section className="admin-card mt-8">
        <h2 className="text-lg font-black">Изображение категории</h2>
        <p className="mt-2 text-sm text-stone-600">
          JPEG, PNG, WebP или AVIF до 5 MiB. При замене прежний файл удаляется
          после сохранения metadata.
        </p>
        {category.imagePublicUrl ? (
          // Public Storage URL is generated by the server from trusted metadata.
          // eslint-disable-next-line @next/next/no-img-element
          <img
            alt=""
            className="mt-4 h-32 w-48 rounded-lg object-cover"
            src={category.imagePublicUrl}
          />
        ) : null}
        <form
          action={uploadCategoryImageAction}
          className="mt-4 flex flex-wrap items-end gap-3"
        >
          <input name="category_id" type="hidden" value={category.id} />
          <label className="field-label">
            Файл
            <input
              accept="image/jpeg,image/png,image/webp,image/avif"
              className="field"
              name="image"
              required
              type="file"
            />
          </label>
          <SubmitButton>Загрузить изображение</SubmitButton>
        </form>
      </section>
      <section className="admin-card mt-8">
        <h2 className="text-lg font-black">Архив</h2>
        <p className="mt-2 text-sm text-stone-600">
          Категорию с активными товарами или подкатегориями архивировать нельзя.
          История slug сохраняется.
        </p>
        <form action={setCategoryArchivedAction} className="mt-4">
          <input name="id" type="hidden" value={category.id} />
          <input
            name="archived"
            type="hidden"
            value={category.archivedAt ? "false" : "true"}
          />
          <ConfirmSubmitButton
            message={
              category.archivedAt
                ? "Восстановить категорию как черновик?"
                : "Архивировать категорию?"
            }
          >
            {category.archivedAt ? "Восстановить" : "Архивировать"}
          </ConfirmSubmitButton>
        </form>
      </section>
    </main>
  );
}
